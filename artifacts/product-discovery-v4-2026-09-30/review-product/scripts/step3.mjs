import { open } from './common.mjs'
import { writeFileSync } from 'node:fs'
const OUT = '/Users/shree/Desktop/Coreweave_AGI_Hackthon/faultlab/artifacts/product-discovery-v4-2026-09-30/review-product/screenshots'
const { browser, page, errors, offsite } = await open()
const log = []
await page.goto('http://127.0.0.1:18432/')
await page.waitForTimeout(1500)
await page.getByLabel('Execution profile', { exact: true }).selectOption('live-v1')
await page.waitForTimeout(500)
await page.getByLabel('Reviewed agent', { exact: true }).selectOption('smolagents-v2')
await page.getByLabel('Campaign mode', { exact: true }).selectOption('learn')
await page.getByLabel('Discovery protocol', { exact: true }).selectOption('faultlab-discovery/v4-history-replay')
await page.waitForTimeout(300)
await page.getByRole('button', { name: 'Create campaign' }).click()
await page.waitForTimeout(2500)
const saved = page.getByRole('region', { name: 'Saved campaign plan' })
const replay = page.getByRole('region', { name: 'Frozen history replay list' })
log.push({ step: 'M4 created', replay: await replay.innerText() })
await replay.locator('summary', { hasText: 'Replay rule' }).click()
await replay.screenshot({ path: OUT + '/05-v4b-plan-replay-list.png' })
log.push({ step: 'M4 replay with rule', replay: await replay.innerText() })
const order = await saved.evaluate(node => { const a = node.querySelector('[aria-label="Frozen history replay list"]'), b = node.querySelector('[aria-label="Frozen agent history"]'); return a && b ? !!(a.compareDocumentPosition(b) & Node.DOCUMENT_POSITION_FOLLOWING) : null })
log.push({ step: 'replay list shown before frozen history', value: order })
// Check against the store now
await page.getByRole('button', { name: 'Check against the store now' }).click()
await page.waitForTimeout(1500)
log.push({ step: 'history check', status: await page.getByRole('region', { name: 'Frozen agent history' }).locator('[role=status]').allInnerTexts() })
const history = page.getByRole('region', { name: 'Frozen agent history' })
await history.screenshot({ path: OUT + '/06-v4b-plan-frozen-history-check.png' })
const campaignId = (await page.locator('.run-receipt code').first().innerText()).trim()
log.push({ step: 'campaign', campaignId })
// Start
await page.getByRole('button', { name: /Start campaign/ }).click()
await page.waitForTimeout(1500)
log.push({ step: 'after start', status: await page.locator('[role=status]').allInnerTexts() })
log.push({ errors, offsite })
writeFileSync('/Users/shree/FaultLab_Scratch/review-product-v4/pw/step3.json', JSON.stringify(log, null, 2))
console.log(JSON.stringify(log, null, 2))
await browser.close()
