import { open } from './common.mjs'
import { writeFileSync } from 'node:fs'
const OUT = '/Users/shree/Desktop/Coreweave_AGI_Hackthon/faultlab/artifacts/product-discovery-v4-2026-09-30/review-product/screenshots'
const { browser, page, errors, offsite } = await open()
const log = []
await page.goto('http://127.0.0.1:18432/')
await page.waitForTimeout(1500)
await page.getByLabel('Execution profile', { exact: true }).selectOption('live-v1')
await page.waitForTimeout(800)
await page.getByLabel('Reviewed agent', { exact: true }).selectOption('smolagents-v2')
await page.waitForTimeout(500)
const setup = page.getByRole('region', { name: 'New campaign setup' })
log.push({ step: 'agent selected', text: (await setup.innerText()).slice(0, 3000) })
const register = page.getByRole('button', { name: 'Register configured agent' })
if (await register.count()) { await register.click(); await page.waitForTimeout(1500) }
log.push({ step: 'after register', status: await page.locator('[role=status]').allInnerTexts() })
await page.getByLabel('Campaign mode', { exact: true }).selectOption('learn')
await page.waitForTimeout(500)
const chooser = page.getByLabel('Discovery protocol', { exact: true })
log.push({ step: 'chooser options', options: await chooser.locator('option').allInnerTexts(), selected: await chooser.inputValue() })
await chooser.selectOption('faultlab-discovery/v4-history-replay')
await page.waitForTimeout(500)
log.push({ step: 'v4 chosen', text: await setup.innerText() })
await setup.screenshot({ path: OUT + '/01-chooser-v4-before-history.png' })
await page.getByRole('button', { name: 'Create campaign' }).click()
await page.waitForTimeout(2500)
const saved = page.getByRole('region', { name: 'Saved campaign plan' })
log.push({ step: 'E4 created (empty history)', plan: await saved.innerText() })
await saved.screenshot({ path: OUT + '/02-v4-plan-empty-history.png' })
// A v3 plan created at the same moment, for the empty-history comparison.
await page.getByLabel('Discovery protocol', { exact: true }).selectOption('faultlab-discovery/v3-history')
await page.waitForTimeout(300)
await page.getByRole('button', { name: 'Create campaign' }).click()
await page.waitForTimeout(2500)
log.push({ step: 'E3 created (empty history)', plan: (await page.getByRole('region', { name: 'Saved campaign plan' }).innerText()).slice(0, 1500) })
log.push({ errors, offsite })
writeFileSync('/Users/shree/FaultLab_Scratch/review-product-v4/pw/step1.json', JSON.stringify(log, null, 2))
console.log(JSON.stringify(log, null, 2).slice(0, 12000))
await browser.close()
